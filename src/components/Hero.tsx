'use client';

import React, { useState } from 'react';
import { Search, ArrowRight, Sparkles, BookOpen, Calendar, Loader2 } from 'lucide-react';
import styles from './Hero.module.css';

interface HeroProps {
  onSearch: (city: string, country?: string) => void;
  onExplorePlan: (city: string, country?: string, days?: number) => void;
  onSelectStory: (city: string, country?: string) => void;
  isLoadingStory?: boolean;
}

const POPULAR_CITIES = [
  { city: 'Kyoto', country: 'Japan' },
  { city: 'Paris', country: 'France' },
  { city: 'Amalfi Coast', country: 'Italy' },
  { city: 'Swiss Alps', country: 'Switzerland' },
  { city: 'Bali', country: 'Indonesia' },
  { city: 'Goa', country: 'India' },
  { city: 'Pune', country: 'India' },
];

export const Hero: React.FC<HeroProps> = ({
  onSearch,
  onExplorePlan,
  onSelectStory,
  isLoadingStory = false,
}) => {
  const [query, setQuery] = useState('');
  const [days, setDays] = useState(5);
  const [isOpeningPlan, setIsOpeningPlan] = useState(false);

  const parseQuery = (str: string) => {
    const parts = str.split(',').map((p) => p.trim());
    return {
      city: parts[0] || str.trim(),
      country: parts[1] || '',
    };
  };

  const handlePlan = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (!query.trim()) return;
    setIsOpeningPlan(true);
    const { city, country } = parseQuery(query);
    onExplorePlan(city, country, days);
    setTimeout(() => setIsOpeningPlan(false), 600);
  };

  const handleStory = () => {
    if (!query.trim()) return;
    const { city, country } = parseQuery(query);
    onSelectStory(city, country);
  };

  const selectCity = (city: string, country: string) => {
    setQuery(`${city}, ${country}`);
  };

  return (
    <section className={styles.hero} id="top">
      <div className={styles.heroContainer}>
        {/* Badge */}
        <div className={styles.badge}>
          <Sparkles size={13} />
          <span>AI-Powered Autonomous Travel Guide</span>
        </div>

        {/* Main Title */}
        <h1 className={styles.title}>
          Travel planning made effortless.
        </h1>

        {/* Subtitle */}
        <p className={styles.subtitle}>
          Enter any destination to instantly get curated cultural stories, voice audio narrations,
          and personalized day-by-day itineraries generated by AI agents.
        </p>

        {/* Search Widget */}
        <form className={styles.searchBox} onSubmit={handlePlan}>
          <div className={styles.searchInputRow}>
            <Search size={18} className={styles.searchIcon} />
            <input
              type="text"
              className={styles.searchInput}
              placeholder="Search destination (e.g. Kyoto, Japan or Rome, Italy)..."
              value={query}
              onChange={(e) => setQuery(e.target.value)}
            />
          </div>

          <div className={styles.searchActions}>
            <div className={styles.daysSelect}>
              <Calendar size={14} />
              <span>Duration:</span>
              <select
                className={styles.selectInput}
                value={days}
                onChange={(e) => setDays(Number(e.target.value))}
              >
                <option value={3}>3 Days</option>
                <option value={5}>5 Days</option>
                <option value={7}>7 Days</option>
                <option value={10}>10 Days</option>
                <option value={14}>14 Days</option>
              </select>
            </div>

            <div className={styles.btnGroup}>
              <button
                type="button"
                className={styles.storyBtn}
                onClick={handleStory}
                disabled={!query.trim() || isLoadingStory}
              >
                {isLoadingStory ? (
                  <>
                    <Loader2 size={14} className="animate-spin" style={{ display: 'inline', marginRight: '6px' }} />
                    Loading Story...
                  </>
                ) : (
                  <>
                    <BookOpen size={14} style={{ display: 'inline', marginRight: '6px' }} />
                    Read Story
                  </>
                )}
              </button>
              <button
                type="submit"
                className={styles.planBtn}
                disabled={!query.trim()}
              >
                {isOpeningPlan ? (
                  <>
                    <Loader2 size={14} className="animate-spin" />
                    <span>Opening Planner...</span>
                  </>
                ) : (
                  <>
                    <span>Plan Itinerary</span>
                    <ArrowRight size={14} />
                  </>
                )}
              </button>
            </div>
          </div>
        </form>

        {/* Quick Suggestions */}
        <div className={styles.quickTags}>
          <span className={styles.tagLabel}>Popular:</span>
          {POPULAR_CITIES.map((c) => (
            <button
              key={c.city}
              type="button"
              className={styles.tagBtn}
              onClick={() => {
                selectCity(c.city, c.country);
                onSelectStory(c.city, c.country);
              }}
            >
              {c.city}
            </button>
          ))}
        </div>
      </div>
    </section>
  );
};
